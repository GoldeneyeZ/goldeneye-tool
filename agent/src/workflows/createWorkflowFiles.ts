  "  if (!source.ok) continue;",
  "  if (!source.source.includes(\"token\")) continue;",
  "  const callers = await gcal.callers(hit.qualifiedName, { depth: 1, limit: 20 });",
  "  evidence.push({ hit, source, callers });",
  "}",
  "return evidence;",
  "```",
